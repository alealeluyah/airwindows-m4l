#!/usr/bin/env python3
"""Build the v8ui display script for each device from the approved design.

    python3 tools/build_ui.py [--decisions design/decisions.json] [--only Category]

For each category, writes javascript/aw_ui_<Category>.js =
    design/lib.js + design/mgcanvas.js + design/designs/<Category>.js + design/runtime_max.js
with the approved option id (from decisions.json; the first option when none is approved)
and Live's Dark and Light theme colours. Prints the option used per category.
"""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"
OUT = ROOT / "javascript"


def option_ids(src):
    return re.findall(r'\bid:\s*"([^"]+)"', src)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--decisions", default=str(DESIGN / "decisions.json"))
    ap.add_argument("--only", action="append")
    ap.add_argument("--log", default="", help="debug log file written by the device displays")
    ap.add_argument("--choose", action="append", default=[], help="Category=Option, overrides decisions.json")
    a = ap.parse_args()

    decisions = json.loads(Path(a.decisions).read_text()) if Path(a.decisions).exists() else {}
    final_path = DESIGN / "final.json"
    final = json.loads(final_path.read_text()) if final_path.exists() else {}
    for c in a.choose:
        cat, opt = c.split("=", 1)
        final[cat] = opt.split("+")
    themes = json.loads((DESIGN / "themes.json").read_text())
    lib = (DESIGN / "lib.js").read_text()
    mgc = (DESIGN / "mgcanvas.js").read_text().replace(
        'if (typeof module !== "undefined") module.exports = { makeCanvas };', "")
    runtime = (DESIGN / "runtime_max.js").read_text()
    OUT.mkdir(exist_ok=True)
    chosen_all = {}

    for f in sorted((DESIGN / "designs").glob("*.js")):
        cat = f.stem
        if a.only and cat not in a.only:
            continue
        src = f.read_text()
        ids = option_ids(src)
        # views: design/final.json, else the approved option, else the first option
        views = final.get(cat) or [decisions.get(cat, {}).get("option") or ids[0]]
        bad = [v for v in views if v not in ids]
        if bad:
            raise SystemExit(f"{cat}: views {bad} not in {ids}")
        chosen = "+".join(views)
        rt = (runtime.replace("__CATEGORY__", json.dumps(cat))
                     .replace("__VIEWS__", json.dumps(views))
                     .replace("__THEMES__", json.dumps(themes))
                     .replace("__LOG__", json.dumps(a.log)))
        body = "\n".join([
            f"// Generated by tools/build_ui.py for Airwindows {cat}, option {chosen}. Do not edit.",
            lib, mgc, src, rt])
        (OUT / f"aw_ui_{cat}.js").write_text(body)
        chosen_all[cat] = chosen
        print(f"{cat}: views {chosen}")

    man = json.loads(subprocess.run(["node", str(DESIGN / "manifest.js"), json.dumps(chosen_all)],
                                    check=True, capture_output=True, text=True).stdout)
    path = OUT / "aw_ui_manifest.json"
    old = json.loads(path.read_text()) if path.exists() else {}
    old.update({k: v for k, v in man.items() if k in chosen_all})
    path.write_text(json.dumps(old, indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
